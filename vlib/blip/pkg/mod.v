// vlib/blip/pkg/mod.v -- packages, tools, workspaces (roadmap Track G).
//
// Grows the `blip pkg` seed into real package management, behind one
// module so the CLI stays thin and the pure parts stay unit-testable:
//
//   * G1 version resolution: `blip.mod` declares requirements, `pkg update`
//     resolves every requester to one pin and records it in blip.lock.
//   * G2 verified installs: the lock carries a content checksum, computed
//     at install and re-checked by `pkg verify` (and by reinstalling an
//     already-installed package). Tampering fails loudly.
//   * G5 workspaces: `(workspace (members a b))` folds member manifests
//     into one universe with one lockfile; `path:` requirements copy
//     local directories in for local development.
//
// Everything networked goes through git against the package URL, which is
// `https://github.com/<owner>/<repo>.git` unless BLIP_PKG_MIRROR is set --
// then `<mirror>/<owner>/<repo>`, which is how the fixtures install from
// local repos with no network, and how a private mirror would work. A
// registry/index is deliberately out of v2 (roadmap: registry later).
module pkg

import crypto.sha256
import encoding.hex
import os
import blip.manifest

// Pin is one blip.lock line: the package, the resolved ref, the commit it
// was taken at, and the content checksum G2 verifies. Path packages record
// ref `path:<root-relative dir>` and sha `-`: they are not versioned, they
// are synced.
pub struct Pin {
pub mut:
	name     string
	ref      string
	sha      string
	checksum string
}

// From is one requester of a package: which manifest asked, from which
// directory, and what for. Error messages name the requester, so a
// conflicting pair points at both manifests instead of reporting
// "cannot resolve" with no address.
pub struct From {
pub:
	requester string
	req       string
	dir       string
}

// parse_spec splits `owner/repo[@ref]`, defaulting ref to HEAD. An empty
// owner means the spec is not a remote package spec.
pub fn parse_spec(spec string) (string, string, string) {
	mut ref := 'HEAD'
	mut path := spec
	if at := spec.index('@') {
		if at >= 0 {
			path = spec[..at]
			ref = spec[at + 1..]
		}
	}
	slash := path.index('/') or { return '', '', '' }
	owner := path[..slash]
	repo := path[slash + 1..]
	if owner == '' || repo == '' || repo.contains('/') {
		return '', '', ''
	}
	return owner, repo, ref
}

// read_lock reads blip.lock in dir. A missing file is an empty universe,
// not an error: a fresh project has no lock yet. Three-field lines (the
// v1 shape, no checksum) read with an empty checksum; G2 treats a missing
// checksum as a failure that `pkg update` fixes, loudly.
pub fn read_lock(dir string) []Pin {
	src := os.read_file(os.join_path(dir, 'blip.lock')) or { return []Pin{} }
	mut out := []Pin{}
	for line in src.split_into_lines() {
		t := line.trim_space()
		if t == '' || t.starts_with('#') {
			continue
		}
		parts := t.split(' ')
		if parts.len < 3 {
			continue
		}
		mut sum := ''
		if parts.len >= 4 {
			sum = parts[3]
		}
		out << Pin{
			name:     parts[0]
			ref:      parts[1]
			sha:      parts[2]
			checksum: sum
		}
	}
	return out
}

// write_lock rewrites blip.lock in dir, sorted by name so two runs over
// the same universe produce byte-identical files.
pub fn write_lock(dir string, pins []Pin) ! {
	mut ordered := pins.clone()
	ordered.sort(a.name < b.name)
	mut sb := '# blip.lock -- installed packages. Regenerated by `blip pkg`.\n'
	for p in ordered {
		sb += '${p.name} ${p.ref} ${p.sha} ${p.checksum}\n'
	}
	os.write_file(os.join_path(dir, 'blip.lock'), sb)!
}

// pin_of finds a package in a pin list, or none.
pub fn pin_of(pins []Pin, name string) ?Pin {
	for p in pins {
		if p.name == name {
			return p
		}
	}
	return none
}

// package_url maps a package name to the git URL it clones from. The
// mirror override exists so fixtures (and private mirrors) do not touch
// the network: with BLIP_PKG_MIRROR=/srv/mirror, `acme/db` clones from
// /srv/mirror/acme/db.
pub fn package_url(name string) string {
	base := os.getenv('BLIP_PKG_MIRROR')
	if base != '' {
		return os.join_path(base, name)
	}
	return 'https://github.com/${name}.git'
}

// norm_version strips a leading `v` so `v1.2.0` and `1.2.0` are the same
// version everywhere reqs and tags meet.
fn norm_version(v string) string {
	mut s := v.trim_space()
	if s.starts_with('v') || s.starts_with('V') {
		s = s[1..]
	}
	return s
}

// version_parts parses `1.2.3` into numbers, or none when any part is not
// a number. Unparseable names (branches like `main`) never compare as
// versions; they only match literally.
fn version_parts(v string) ?[]int {
	s := norm_version(v)
	if s == '' {
		return none
	}
	mut out := []int{}
	for part in s.split('.') {
		n := part.int()
		if n.str() != part && !(part.starts_with('0') && n == 0) {
			return none
		}
		out << n
	}
	return out
}

// compare_versions orders versions numerically, treating a missing tail
// as zeros (`1.2` == `1.2.0`). Unparseable input compares as 0/0/..., so
// it only ever equals itself through the literal path in satisfies.
pub fn compare_versions(a string, b string) int {
	pa := version_parts(a) or { []int{} }
	pb := version_parts(b) or { []int{} }
	mut n := pa.len
	if pb.len > n {
		n = pb.len
	}
	mut i := 0
	for i < n {
		av := if i < pa.len { pa[i] } else { 0 }
		bv := if i < pb.len { pb[i] } else { 0 }
		if av < bv {
			return -1
		}
		if av > bv {
			return 1
		}
		i++
	}
	return 0
}

// satisfies reports whether tag meets req. `>=1.2` is a floor, `=1.2` and
// a bare `1.2` are exact (modulo the `v` prefix), and anything else -- a
// branch, a sha -- matches literally. `path:` reqs never satisfy here;
// the universe handles them before resolution.
pub fn satisfies(tag string, req string) bool {
	r := req.trim_space()
	if r.starts_with('path:') {
		return false
	}
	if r.starts_with('>=') {
		want := norm_version(r[2..])
		_ = version_parts(tag) or { return false }
		_ = version_parts(want) or { return false }
		return compare_versions(tag, want) >= 0
	}
	mut want := r
	if want.starts_with('=') {
		want = want[1..]
	}
	if tag == want {
		return true
	}
	_ = version_parts(tag) or { return false }
	_ = version_parts(want) or { return false }
	return compare_versions(tag, want) == 0
}

// resolve picks the pin for one package: the maximum tag satisfying every
// req. Two members asking for different floors (`>=1.0.0` and `>=1.1.0`)
// resolve to one pin (the max); an exact plus a floor it meets resolves
// to the exact. Nothing satisfying is an error naming every req, because
// "cannot resolve" without the reqs is unactionable.
pub fn resolve(name string, reqs []string, tags []string) !string {
	mut best := ''
	for t in tags {
		mut ok := true
		for r in reqs {
			if !satisfies(t, r) {
				ok = false
				break
			}
		}
		if !ok {
			continue
		}
		if best == '' || compare_versions(t, best) > 0 {
			best = t
		}
	}
	if best == '' {
		return error('blip: cannot resolve ${name}: no tag meets [${reqs.join(', ')}] (tags: ${tags.join(', ')})')
	}
	return best
}

// checksum_dir hashes a package directory: every file except the `.git`
// tree, sorted by slash-separated relative path, each as
// `relpath + NUL + content + NUL`. Sorting makes it deterministic;
// skipping `.git` makes it about the shipped content, not the history.
pub fn checksum_dir(dir string) !string {
	mut rels := []string{}
	collect_files(dir, '', mut rels)
	rels.sort()
	mut buf := []u8{}
	for r in rels {
		buf << r.bytes()
		buf << 0
		buf << os.read_file(os.join_path(dir, r))!.bytes()
		buf << 0
	}
	return hex.encode(sha256.sum(buf))
}

fn collect_files(base string, rel string, mut out []string) {
	full := if rel == '' { base } else { os.join_path(base, rel) }
	for e in os.ls(full) or { return } {
		if e == '.git' {
			continue
		}
		r := if rel == '' { e } else { rel + '/' + e }
		if os.is_dir(os.join_path(base, r)) {
			collect_files(base, r, mut out)
			continue
		}
		out << r
	}
}

// verify_dir recomputes a package checksum and fails loudly on mismatch.
// The message names the package, not a hash: a hash in the output answers
// nothing, while the name tells the user which line of whose lock to fix.
pub fn verify_dir(dir string, name string, want string) ! {
	if want == '' {
		return error('blip: ${name} has no checksum recorded; run `blip pkg update`')
	}
	got := checksum_dir(dir)!
	if got != want {
		return error('blip: ${name} checksum mismatch (tampered?); remove and reinstall, or run `blip pkg update`')
	}
}

// copy_package copies a local directory into place for a `path:` dep,
// skipping history. Re-copying over an existing dir removes it first, so
// a stale file the source deleted does not linger in the installed copy.
pub fn copy_package(src string, dst string) ! {
	if os.is_dir(dst) {
		os.rmdir_all(dst)!
	}
	os.mkdir_all(dst)!
	copy_tree(src, dst)!
}

fn copy_tree(src string, dst string) ! {
	for e in os.ls(src) or { return error('blip: cannot read ${src}: ${err.msg()}') } {
		if e == '.git' {
			continue
		}
		s := os.join_path(src, e)
		d := os.join_path(dst, e)
		if os.is_dir(s) {
			os.mkdir_all(d)!
			copy_tree(s, d)!
			continue
		}
		os.write_file(d, os.read_file(s)!)!
	}
}

// list_remote_tags maps tag name to commit sha for a package URL, preferring
// the peeled (`^{}`) commit for annotated tags. `git ls-remote` works
// against local paths too, which is what keeps the fixtures offline.
pub fn list_remote_tags(url string) !map[string]string {
	r := os.exec(['git', 'ls-remote', '--tags', url])
	if r.exit_code != 0 {
		return error('blip: cannot list tags of ${url}: ${r.output.trim_space()}')
	}
	mut out := map[string]string{}
	for line in r.output.split_into_lines() {
		f := line.split('\t')
		if f.len != 2 {
			continue
		}
		sha := f[0].trim_space()
		raw := f[1].trim_space()
		peeled := raw.ends_with('^{}')
		refname := if peeled { raw[..raw.len - 3] } else { raw }
		if !refname.starts_with('refs/tags/') {
			continue
		}
		tag := refname['refs/tags/'.len..]
		// The peeled commit overwrites the tag object: for an annotated
		// tag the object line arrives first, the commit second.
		if peeled || tag !in out {
			out[tag] = sha
		}
	}
	return out
}

// ensure_cloned clones url into dir unless it already holds a repo.
pub fn ensure_cloned(url string, dir string) ! {
	if os.is_dir(os.join_path(dir, '.git')) {
		return
	}
	os.mkdir_all(os.dir(dir))!
	r := os.exec(['git', 'clone', '--quiet', url, dir])
	if r.exit_code != 0 {
		return error('blip: clone of ${url} failed: ${r.output.trim_space()}')
	}
}

// checkout_sha moves a clone to exactly sha, detached. Checking out the
// sha rather than the tag is what makes the install reproducible: a tag
// can move, a sha cannot.
pub fn checkout_sha(dir string, sha string) ! {
	r := os.exec(['git', '-C', dir, 'checkout', '--quiet', sha])
	if r.exit_code != 0 {
		return error('blip: cannot check out ${sha} in ${dir}: ${r.output.trim_space()}')
	}
}

// head_sha answers the commit a directory currently holds.
pub fn head_sha(dir string) string {
	r := os.exec(['git', '-C', dir, 'rev-parse', 'HEAD'])
	if r.exit_code != 0 {
		return ''
	}
	return r.output.trim_space()
}

// fetch_all updates a clone's view of its origin, so `update` sees tags
// published since the clone.
pub fn fetch_all(dir string) ! {
	r := os.exec(['git', '-C', dir, 'fetch', '--quiet', '--tags', 'origin'])
	if r.exit_code != 0 {
		return error('blip: cannot fetch in ${dir}: ${r.output.trim_space()}')
	}
}

// Universe is everything one `pkg update` resolves: each dep name with
// every requester that asked for it, plus the member dirs (used in place,
// never copied).
pub struct Universe {
pub mut:
	reqs    map[string][]From
	members []string
}

// collect_universe reads root/blip.mod plus every workspace member
// manifest. The root manifest must exist: without it there is no project
// whose universe to build. Member entries are directory names under root;
// a member without its own blip.mod is an error naming the directory,
// because a silent skip would resolve a universe the tree does not have.
pub fn collect_universe(root string) !Universe {
	mod_path := os.join_path(root, 'blip.mod')
	src := os.read_file(mod_path) or {
		return error('blip: no blip.mod in ${root}; run `blip pkg install <owner/repo>` for ad-hoc installs, or add a manifest')
	}
	m := manifest.parse(src) or { return error(err.msg()) }
	mut u := Universe{}
	for d in m.deps {
		u.reqs[d.name] << From{
			requester: 'blip.mod'
			req:       d.req
			dir:       root
		}
	}
	for member in m.workspace {
		mdir := os.join_path(root, member)
		mpath := os.join_path(mdir, 'blip.mod')
		msrc := os.read_file(mpath) or {
			return error('blip: workspace member `${member}` has no blip.mod')
		}
		mm := manifest.parse(msrc) or { return error(err.msg()) }
		u.members << member
		for d in mm.deps {
			u.reqs[d.name] << From{
				requester: '${member}/blip.mod'
				req:       d.req
				dir:       mdir
			}
		}
	}
	u.members.sort()
	return u
}

// dep_names lists the universe's packages, sorted for determinism.
pub fn (u Universe) dep_names() []string {
	mut names := u.reqs.keys()
	names.sort()
	return names
}

// is_path_req reports a `path:` requirement and its directory.
pub fn is_path_req(req string) (bool, string) {
	if req.starts_with('path:') {
		return true, req[5..]
	}
	return false, ''
}

// resolve_universe resolves every dep to a pin. Path deps must agree on
// one directory across requesters (recorded root-relative); version deps
// resolve to the max tag meeting every req. The error names the package
// and every requester, because a conflict the message does not locate is
// a conflict nobody can fix.
pub fn resolve_universe(root string, u Universe) ![]Pin {
	mut pins := []Pin{}
	for name in u.dep_names() {
		froms := u.reqs[name]
		mut reqs := []string{}
		for f in froms {
			reqs << f.req
		}
		mut paths := []string{}
		for r in reqs {
			ok, p := is_path_req(r)
			if ok {
				paths << p
			}
		}
		if paths.len > 0 {
			if reqs.len != paths.len {
				mut who := []string{}
				for f in froms {
					who << '${f.requester} wants ${f.req}'
				}
				return error('blip: ${name} mixes path and version requirements: ${who.join('; ')}')
			}
			// Path reqs resolve against the requesting manifest's own
			// directory, so `path:../shared` means the same tree whether
			// the root or a member writes it. Existence is checked here,
			// before anything is cloned: a missing source must fail the
			// resolve with the requester named, not leave half a tree
			// behind after the remotes installed.
			mut srcs := []string{}
			for i, r in reqs {
				_, p := is_path_req(r)
				j := if os.is_abs_path(p) { p } else { os.join_path(froms[i].dir, p) }
				if !os.is_dir(j) {
					return error('blip: ${name}: `${r}` from ${froms[i].requester} does not exist (looked in ${j})')
				}
				srcs << os.real_path(j)
			}
			first := srcs[0]
			for s in srcs[1..] {
				if s != first {
					mut who := []string{}
					for f in froms {
						who << '${f.requester} wants ${f.req}'
					}
					return error('blip: ${name} path requirements disagree: ${who.join('; ')}')
				}
			}
			// Recorded root-relative so a copied tree stays valid.
			rel := rel_to_root(root, first)
			pins << Pin{
				name: name
				ref:  'path:' + rel
				sha:  '-'
			}
			continue
		}
		tags := list_remote_tags(package_url(name))!
		mut names_ := []string{}
		for t in tags.keys() {
			names_ << t
		}
		ref := resolve(name, reqs, names_) or {
			mut who := []string{}
			for f in froms {
				who << '${f.requester} wants `${f.req}`'
			}
			return error('${err.msg()} (requested by ${who.join(', ')})')
		}
		pins << Pin{
			name: name
			ref:  ref
			sha:  tags[ref]
		}
	}
	return pins
}

// rel_to_root expresses an absolute path relative to root when inside it,
// so locks stay portable across checkouts. Outside paths stay absolute.
fn rel_to_root(root string, abs string) string {
	r := os.real_path(root)
	a := os.real_path(abs)
	if a.starts_with(r + os.path_separator) {
		return a[r.len + 1..]
	}
	return abs
}

// install_pins materializes pins into blip_modules/: remotes by clone and
// exact-sha checkout, paths by fresh copy. Every remote gets its checksum
// recorded (G2); path copies are checksummed too, so `verify` judges them
// by the same rule.
pub fn install_pins(root string, mut pins []Pin) ! {
	for i, p in pins {
		dst := os.join_path(os.join_path(os.join_path(root, 'blip_modules'), os.dir(p.name)),
			os.file_name(p.name))
		if p.ref.starts_with('path:') {
			src := os.join_path(root, p.ref[5..])
			copy_package(src, dst)!
			pins[i].checksum = checksum_dir(dst)!
			continue
		}
		ensure_cloned(package_url(p.name), dst)!
		fetch_all(dst)!
		checkout_sha(dst, p.sha)!
		if head_sha(dst) != p.sha {
			return error('blip: ${p.name} did not land on ${p.sha}')
		}
		pins[i].checksum = checksum_dir(dst)!
	}
}

// update resolves the whole universe to fresh pins and installs them: the
// deterministic `pkg update` behind G1. Re-resolving (not reusing the old
// lock) is what moves pins forward; the lock is rewritten sorted.
pub fn update(root string) ![]Pin {
	u := collect_universe(root)!
	if u.dep_names().len == 0 {
		return []Pin{}
	}
	mut pins := resolve_universe(root, u)!
	install_pins(root, mut pins)!
	write_lock(root, pins)!
	return pins
}

// install reproduces the locked universe without re-resolving (G5): remote
// pins are enforced by exact sha, path pins re-synced from their sources.
// A missing lock is an error pointing at `update`, because installing
// with nothing pinned would resolve -- the opposite of reproducible.
pub fn install(root string) ![]Pin {
	mut pins := read_lock(root)
	if pins.len == 0 {
		return error('blip: nothing locked; run `blip pkg update` to resolve ./blip.mod first')
	}
	for i, p in pins {
		dst := os.join_path(os.join_path(os.join_path(root, 'blip_modules'), os.dir(p.name)),
			os.file_name(p.name))
		if p.ref.starts_with('path:') {
			src := os.join_path(root, p.ref[5..])
			copy_package(src, dst)!
			pins[i].checksum = checksum_dir(dst)!
			continue
		}
		if !os.is_dir(os.join_path(dst, '.git')) {
			ensure_cloned(package_url(p.name), dst)!
		}
		checkout_sha(dst, p.sha)!
		if head_sha(dst) != p.sha {
			return error('blip: ${p.name} did not land on ${p.sha}')
		}
		verify_dir(dst, p.name, p.checksum)!
	}
	write_lock(root, pins)!
	return pins
}

// verify checks every locked remote against its recorded checksum and
// reports each mismatch. No lock, or an entry with no checksum, is a
// failure with a fix (`update`), not silence.
pub fn verify(root string) ![]string {
	pins := read_lock(root)
	if pins.len == 0 {
		return error('blip: nothing locked; run `blip pkg update` first')
	}
	mut bad := []string{}
	for p in pins {
		dst := os.join_path(os.join_path(os.join_path(root, 'blip_modules'), os.dir(p.name)),
			os.file_name(p.name))
		if !os.is_dir(dst) {
			bad << '${p.name} missing from blip_modules/'
			continue
		}
		verify_dir(dst, p.name, p.checksum) or { bad << err.msg() }
	}
	return bad
}

// install_one installs a single explicit `owner/repo[@ref]` spec: the
// ad-hoc path that needs no manifest. An already-installed package at
// the same ref is verified, not re-cloned -- and a checksum mismatch
// fails instead of silently overwriting, the same rule as everywhere.
pub fn install_one(root string, spec string) !Pin {
	owner, repo, ref := parse_spec(spec)
	if owner == '' {
		return error('blip: pkg install wants <owner/repo>[@ref], got `${spec}`')
	}
	name := '${owner}/${repo}'
	dst := os.join_path(os.join_path(os.join_path(root, 'blip_modules'), owner), repo)
	mut pins := read_lock(root)
	if old := pin_of(pins, name) {
		// Verify first, compare refs second: a tampered tree fails loudly
		// even when the requested ref differs from the lock. Silently
		// checking out over tampering would bless it.
		if os.is_dir(os.join_path(dst, '.git')) && old.checksum != '' {
			verify_dir(dst, name, old.checksum)!
		}
		if old.ref == ref {
			return old
		}
	}
	ensure_cloned(package_url(name), dst)!
	if ref != 'HEAD' {
		r := os.exec(['git', '-C', dst, 'checkout', '--quiet', ref])
		if r.exit_code != 0 {
			return error('blip: ${name} has no ref `${ref}`: ${r.output.trim_space()}')
		}
	}
	sha := head_sha(dst)
	if sha == '' {
		return error('blip: installed ${name} but cannot record its commit')
	}
	sum := checksum_dir(dst)!
	mut replaced := false
	for i, l in pins {
		if l.name == name {
			pins[i] = Pin{
				name:     name
				ref:      ref
				sha:      sha
				checksum: sum
			}
			replaced = true
			break
		}
	}
	if !replaced {
		pins << Pin{
			name:     name
			ref:      ref
			sha:      sha
			checksum: sum
		}
	}
	write_lock(root, pins)!
	return Pin{
		name:     name
		ref:      ref
		sha:      sha
		checksum: sum
	}
}

// remove_one deletes an installed package and drops its lock line,
// pruning the emptied owner dir like before.
pub fn remove_one(root string, spec string) !string {
	owner, repo, _ := parse_spec(spec)
	name := if owner != '' { '${owner}/${repo}' } else { spec }
	mut found := false
	for l in read_lock(root) {
		if l.name == name {
			found = true
			break
		}
	}
	if !found {
		return error('blip: ${name} is not installed')
	}
	owner_dir := os.join_path(os.join_path(root, 'blip_modules'), os.dir(name))
	dir := os.join_path(owner_dir, os.file_name(name))
	if os.is_dir(dir) {
		os.rmdir_all(dir)!
	}
	if os.is_dir(owner_dir) && os.ls(owner_dir) or { [] }.len == 0 {
		os.rmdir_all(owner_dir) or {}
	}
	mut kept := []Pin{}
	for l in read_lock(root) {
		if l.name != name {
			kept << l
		}
	}
	write_lock(root, kept)!
	return name
}
